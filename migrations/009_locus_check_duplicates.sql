SELECT excavation_id, number, count(*) as c,
GROUP_CONCAT(id SEPARATOR ',') as id,
GROUP_CONCAT(site SEPARATOR ',') as site,
GROUP_CONCAT(season SEPARATOR ',') as season,
GROUP_CONCAT(trench SEPARATOR ',') as trench,
GROUP_CONCAT(description SEPARATOR ',') as description

FROM `locus` GROUP BY excavation_id, number HAVING c > 1;

