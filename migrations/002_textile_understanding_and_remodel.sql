LEFT JOIN textile_trench tt ON tt.Textile_ID11 = textile.Textile_ID
LEFT JOIN trench_t t ON tt.Trench_number1 = t.Trench_number
GROUP BY
  b.Pottery_bucket_number1,
  l.Locus_number1,
  tt.Trench_number1,
  t.Year

) b_text LEFT JOIN
(
SELECT
  t.number berenike_t, l.number berenike_l, l.season berenike_season, b.number berenike_b, b.id berenike_b_id
FROM berenike.bucket b
JOIN berenike.locus l ON b.locus_id = l.id
JOIN berenike.trench t ON l.trench_id = t.id
WHERE
  t.site = 'BE' AND
  t.number in ('59', '60', '111', '112', '114', '118', '120', '122', '137')
GROUP BY
  b.id,
  l.id,
  t.id,
  l.season
) b_find
ON textile_t = berenike_t AND textile_season = berenike_season AND textile_l = berenike_l AND textile_b = berenike_b
ORDER BY
CAST(berenike_t AS INT), berenike_season, berenike_l, CAST(berenike_b AS INT),
  textile_t, textile_season, textile_l, textile_b
 
