  tt.Trench_number1 textile_t, t.`Year` textile_season, l.Locus_number1 textile_l, b.Pottery_bucket_number1 textile_b, count(textile.Textile_ID) as count_textiles, GROUP_CONCAT(textile.Textile_ID SEPARATOR '|')
